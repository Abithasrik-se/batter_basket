    for _host in ("localhost", "127.0.0.1"):
        for _port in (5173, 4173, 3000, 8000):
            _origin = f"http://{_host}:{_port}"
            if _origin not in CSRF_TRUSTED_ORIGINS:
                CSRF_TRUSTED_ORIGINS.append(_origin)

